import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const argv = process.argv.slice(2);
const value = (name) => { const i = argv.indexOf(name); if (i < 0) throw new Error(`${name} is required`); return argv[i + 1]; };
const port = Number(value("--port"));
const host = value("--host");
const operationId = value("--operation-id");
const oldAttemptId = value("--old-attempt-id");
const newAttemptId = value("--new-attempt-id");
const newSessionHash = value("--new-session-hash");
const marker = value("--marker");
const provider = argv.includes("--provider") ? value("--provider") : "claude";
const markerSource = argv.includes("--marker-source") ? value("--marker-source") : "unspecified";
const screenshotPath = resolve(value("--screenshot"));
const reportPath = resolve(value("--report"));
const artifactPath = argv.includes("--artifact") ? resolve(value("--artifact")) : null;
const raw = await (await fetch(`http://127.0.0.1:${port}/json`)).json();
const page = (Array.isArray(raw) ? raw : [raw]).find((item) => item.type === "page" && String(item.title || "").includes("GoalPort"));
if (!page?.webSocketDebuggerUrl) throw new Error("GoalPort page unavailable");
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((ok, fail) => { ws.addEventListener("open", ok, { once: true }); ws.addEventListener("error", fail, { once: true }); });
let id = 0;
const pending = new Map();
ws.addEventListener("message", (event) => { const message = JSON.parse(event.data); const waiter = pending.get(message.id); if (!waiter) return; pending.delete(message.id); message.error ? waiter.reject(new Error(message.error.message)) : waiter.resolve(message.result); });
const call = (method, params = {}) => new Promise((ok, fail) => { const callId = ++id; pending.set(callId, { resolve: ok, reject: fail }); ws.send(JSON.stringify({ id: callId, method, params })); });
const expression = host === "electron" ? "window.goalportCore.snapshot()" : "window.__TAURI_INTERNALS__.invoke('core_snapshot')";
const evaluated = await call("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true });
const snapshot = evaluated.result.value;
const domResult = await call("Runtime.evaluate", { expression: `(()=>{const text=document.body.innerText;return {connected:text.includes('Core connected'),marker:text.includes(${JSON.stringify(marker)}),terminal:text.includes('Attempt state updated')&&(text.includes('COMMITTED')||text.includes('FAILED'))};})()`, returnByValue: true });
const dom = domResult.result.value;
const screenshot = await call("Page.captureScreenshot", { format: "png", captureBeyondViewport: false });
const png = Buffer.from(screenshot.data, "base64");
mkdirSync(resolve(screenshotPath, ".."), { recursive: true });
writeFileSync(screenshotPath, png);
const operation = { host, operationId, oldAttemptId, newAttemptId, newSessionHash, attemptId: snapshot.attempt?.id, provider: snapshot.attempt?.provider, coreBuildId: snapshot.buildId, cursor: snapshot.cursor, connected: dom.connected, nativeResponseObserved: dom.marker, terminalObserved: dom.terminal };
const entry = { ...operation, markerSource, artifactSha256: artifactPath ? createHash("sha256").update(readFileSync(artifactPath)).digest("hex") : null, screenshotSha256: createHash("sha256").update(png).digest("hex"), operationSha256: createHash("sha256").update(JSON.stringify(operation)).digest("hex") };
mkdirSync(resolve(reportPath, ".."), { recursive: true });
writeFileSync(reportPath, `${JSON.stringify(entry, null, 2)}\n`);
console.log(JSON.stringify(entry, null, 2));
ws.close();
process.exitCode = entry.attemptId === newAttemptId && entry.provider === provider && dom.connected && dom.marker && dom.terminal ? 0 : 1;
